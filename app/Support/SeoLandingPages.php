    public static function find(string $slug): ?array
    {
        foreach (self::all() as $landing) {
            if ($landing['slug'] === $slug) {
                return $landing;
            }
        }

        return null;
    }

    public static function slugs(): array
    {
        return array_column(self::all(), 'slug');
    }
